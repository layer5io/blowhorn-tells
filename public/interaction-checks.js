// The 13 interaction checks: thresholds and status rules, in one place.
// The page (public/collect-interaction.js) and the Worker (src/report-verdict.js) both import
// this module, so the two sides can never disagree on a status. Every input is a field of the
// interaction report (schemas/interaction-report.schema.json); nothing here reads the DOM.
//
// All thresholds are provisional until calibration on 20+ human runs.

export const INTERACTION_THRESHOLDS = {
  centrePassPx: 1,
  centreFailPx: 0.5,
  premovePassSamples: 3,
  premovePassPathPx: 20,
  pressPassMinMs: 30,
  pressPassMaxMs: 400,
  pressFailMs: 10,
  rhythmMinIntervals: 8,
  rhythmPassCv: 0.15,
  rhythmFailCv: 0.05,
  rhythmPassMeanMs: 60,
  rhythmFailMeanMs: 30,
  dwellPassMinMs: 40,
  dwellPassMaxMs: 250,
  taskPassMs: 1500,
  taskFailMs: 800
};

export const INTERACTION_CHECK_IDS = [
  "int_trusted",
  "int_click_chain",
  "int_click_detail",
  "int_screen_coords",
  "int_coalesced",
  "int_premove",
  "int_centre",
  "int_press",
  "int_key_chain",
  "int_value_source",
  "int_key_rhythm",
  "int_dwell",
  "int_task_speed"
];

const CLICK_ORDER = ["pointerdown", "mousedown", "pointerup", "mouseup", "click"];
const T = INTERACTION_THRESHOLDS;

// Each evaluator returns { status, observed } from the report alone.
const EVALUATORS = {
  int_trusted(report) {
    const clicks = report.click.clicks;
    const eventsSeen = clicks.length + report.typing.counts.keydown + report.typing.counts.input + report.typing.counts.paste;
    if (eventsSeen === 0 && report.typing.untrusted === 0) return na("no task events");
    if (report.typing.untrusted === 0) return result("pass", "every task event is trusted");
    return result("fail", `${report.typing.untrusted} task events were generated by script`);
  },

  int_click_chain(report) {
    const clicks = report.click.clicks;
    if (!clicks.length) return na("no clicks");
    const missing = clicks.filter((click) => !click.chain.includes("pointerdown") && !click.chain.includes("mousedown"));
    if (missing.length) return result("fail", `${missing.length} of ${clicks.length} clicks had no pointerdown or mousedown`);
    const disordered = clicks.filter((click) => !inOrder(click.chain, CLICK_ORDER));
    if (disordered.length) return result("warn", `${disordered.length} of ${clicks.length} clicks had an incomplete or out-of-order press and release`);
    return result("pass", `full press and release chain on all ${clicks.length} clicks`);
  },

  int_click_detail(report) {
    const trusted = trustedClicks(report);
    if (!trusted.length) return na("no trusted clicks");
    const zero = trusted.filter((click) => click.detail === 0);
    if (zero.length) return result("fail", `${zero.length} of ${trusted.length} trusted clicks had click detail 0`);
    return result("pass", `click detail of at least 1 on all ${trusted.length} trusted clicks`);
  },

  int_screen_coords(report) {
    if (report.task.fullscreen) return na("fullscreen, not judged");
    const trusted = trustedClicks(report);
    if (!trusted.length) return na("no trusted clicks");
    const equal = trusted.filter((click) => click.screenMinusClient && click.screenMinusClient.dx === 0 && click.screenMinusClient.dy === 0);
    if (equal.length === trusted.length) return result("fail", "screen and client coordinates are equal on every click");
    return result("pass", "screen and client coordinates differ");
  },

  int_coalesced(report) {
    const values = report.click.clicks.map((click) => click.coalescedMin).filter((value) => value !== null && value !== undefined);
    if (!values.length) return na("no pointer moves before clicks");
    const zero = values.filter((value) => value === 0).length;
    if (zero === values.length) return result("fail", "no coalesced pointer events on any click");
    if (zero) return result("warn", `no coalesced pointer events before ${zero} of ${values.length} clicks`);
    return result("pass", "coalesced pointer events present before every click");
  },

  int_premove(report) {
    const mouse = report.click.clicks.filter((click) => click.pointerType === "mouse");
    if (!mouse.length) return na("no mouse clicks (touch or pen not judged)");
    const samples = mouse.map((click) => click.premoveSamples || 0);
    if (samples.every((count) => count === 0)) return result("fail", "no pointer movement in the second before any click");
    const human = mouse.every((click) => (click.premoveSamples || 0) >= T.premovePassSamples && (click.premovePathPx || 0) > T.premovePassPathPx);
    if (human) return result("pass", `pointer travelled before every click (${Math.min(...samples)} or more samples)`);
    return result("warn", `thin pointer movement before some clicks (${samples.join(", ")} samples)`);
  },

  int_centre(report) {
    const trusted = trustedClicks(report).filter((click) => click.offsetFromCentre);
    if (!trusted.length) return na("no trusted clicks");
    const distances = trusted.map((click) => Math.hypot(click.offsetFromCentre.dx, click.offsetFromCentre.dy));
    const farthest = Math.max(...distances);
    if (farthest > T.centrePassPx) return result("pass", `clicks land off centre (farthest ${round(farthest)} px)`);
    if (farthest > T.centreFailPx) return result("warn", `clicks all within ${T.centrePassPx} px of centre`);
    return result("fail", `every click within ${T.centreFailPx} px of centre`);
  },

  int_press(report) {
    const presses = trustedClicks(report).map((click) => click.pressMs).filter((value) => value !== null && value !== undefined);
    if (!presses.length) return na("no press durations");
    if (presses.every((ms) => ms >= T.pressPassMinMs && ms <= T.pressPassMaxMs)) return result("pass", `press held ${T.pressPassMinMs} to ${T.pressPassMaxMs} ms on every click`);
    if (presses.every((ms) => ms < T.pressFailMs)) return result("fail", `every press under ${T.pressFailMs} ms`);
    return result("warn", `press durations ${presses.map((ms) => round(ms)).join(", ")} ms`);
  },

  int_key_chain(report) {
    const { counts, inputWithoutKeydown } = report.typing;
    if (!counts.keydown && !inputWithoutKeydown) return na("no typed keys");
    if (inputWithoutKeydown > 0) return result("fail", `${inputWithoutKeydown} characters arrived with no key press (insertText-style)`);
    if (counts.keypress < counts.keydown || counts.keyup < counts.keydown || counts.beforeinput < counts.keydown) {
      return result("warn", `keypress or keyup missing on some of ${counts.keydown} keys`);
    }
    return result("pass", `full key chain on all ${counts.keydown} keys`);
  },

  int_value_source(report) {
    const { counts, valueMatches, valueSetterNative, inputWithoutKeydown } = report.typing;
    if (!valueMatches) return na("value not checked");
    if (valueSetterNative === false) return result("fail", "value setter is not the native one");
    if (counts.input === 0) return result("fail", "value present with no input events");
    if (counts.paste > 0) return result("warn", "value arrived by paste");
    if (inputWithoutKeydown > 0) return result("warn", "value arrived without key presses");
    return result("pass", "value matches the typed keys");
  },

  int_key_rhythm(report) {
    const stats = report.typing.intervalMs;
    if (!stats || stats.n < T.rhythmMinIntervals) return na(`fewer than ${T.rhythmMinIntervals} key intervals`);
    const { cv, mean } = stats;
    const observed = `mean ${round(mean)} ms, variation ${round(cv)}`;
    if (cv < T.rhythmFailCv || mean < T.rhythmFailMeanMs) return result("fail", observed);
    if (cv >= T.rhythmPassCv && mean >= T.rhythmPassMeanMs) return result("pass", observed);
    return result("warn", observed);
  },

  int_dwell(report) {
    const stats = report.typing.dwellMs;
    if (!stats || stats.n === 0) return result("fail", "no key holds recorded");
    if (stats.median === 0 && stats.stdDev === 0) return result("fail", "every key hold was 0 ms");
    const observed = `median ${round(stats.median)} ms over ${stats.n} keys`;
    if (stats.stdDev === 0) return result("warn", `every key held for the same time (${observed})`);
    if (stats.median >= T.dwellPassMinMs && stats.median <= T.dwellPassMaxMs) return result("pass", observed);
    return result("warn", observed);
  },

  int_task_speed(report) {
    const { durationMs } = report.task;
    if (durationMs === null) return na("no task duration");
    const observed = `${round(durationMs / 1000)} s from Start to Submit`;
    if (durationMs >= T.taskPassMs) return result("pass", observed);
    if (durationMs >= T.taskFailMs) return result("warn", observed);
    return result("fail", observed);
  }
};

// Every check in INTERACTION_CHECK_IDS, in order, with the provisional flag set. Nothing is
// judged unless the test was completed: an untaken or abandoned test has no evidence to weigh.
export function evaluateInteractionChecks(report) {
  const completed = report.task.completed === true;
  return INTERACTION_CHECK_IDS.map((id) => ({
    id,
    ...(completed ? EVALUATORS[id](report) : na("task not completed")),
    provisional: true
  }));
}

function trustedClicks(report) {
  return report.click.clicks.filter((click) => click.isTrusted);
}

function inOrder(chain, sequence) {
  let cursor = -1;
  for (const type of sequence) {
    const index = chain.indexOf(type, cursor + 1);
    if (index === -1) return false;
    cursor = index;
  }
  return true;
}

function result(status, observed) {
  return { status, observed };
}

function na(observed) {
  return result("na", observed);
}

function round(value) {
  return Math.round(value * 10) / 10;
}
